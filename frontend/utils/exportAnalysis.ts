export interface ExportPayload {
  username: string;
  name?: string | null;
  bio?: string | null;
  profileUrl?: string;
  repositoriesCount?: number;
  followers?: number;
  following?: number;
  skills: Array<{ name: string; repository_count: number; percentage: number }>;
  totalRepositoriesAnalyzed?: number;
  exportedAt?: string;
}

export function generateMarkdownReport(data: ExportPayload): string {
  const exportDate = data.exportedAt || new Date().toISOString().split("T")[0];
  const nameDisplay = data.name ? `${data.name} (@${data.username})` : `@${data.username}`;

  const skillsTable =
    data.skills.length > 0
      ? data.skills
          .map((s) => `| ${s.name} | ${s.repository_count} | ${s.percentage}% |`)
          .join("\n")
      : "| No technical skills detected | - | - |";

  return `# OpenSourceMate Developer Profile Analysis

**User**: [${nameDisplay}](${data.profileUrl || `https://github.com/${data.username}`})
**Export Date**: ${exportDate}
${data.bio ? `**Bio**: ${data.bio}\n` : ""}
## Overview & Activity
- **Public Repositories**: ${data.repositoriesCount ?? 0}
- **Followers**: ${data.followers ?? 0}
- **Following**: ${data.following ?? 0}
- **Repositories Analyzed**: ${data.totalRepositoriesAnalyzed ?? 0}

## Technical Skills Breakdown
| Technology / Skill | Repositories | Compatibility Share |
| :--- | :---: | :---: |
${skillsTable}

---
*Generated by [OpenSourceMate](https://github.com/Muskankr/OpenSourceMate) - AI-powered open-source contribution assistant.*
`;
}

export function generateJsonReport(data: ExportPayload): string {
  return JSON.stringify(
    {
      app: "OpenSourceMate",
      version: "0.1.0",
      exportedAt: data.exportedAt || new Date().toISOString(),
      ...data,
    },
    null,
    2
  );
}

export function downloadFile(content: string, filename: string, mimeType: string): void {
  if (typeof window === "undefined") return;

  const blob = new Blob([content], { type: mimeType });
  const url = URL.createObjectURL(blob);
  const link = document.createElement("a");
  link.href = url;
  link.download = filename;
  document.body.appendChild(link);
  link.click();
  document.body.removeChild(link);
  URL.revokeObjectURL(url);
}
